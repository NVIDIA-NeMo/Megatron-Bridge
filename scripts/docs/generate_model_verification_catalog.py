def render_model_section(models: list[dict[str, object]]) -> str:
    """Render generated verification selectors for one canonical model guide."""
    lines = [
        MODEL_SECTION_START,
        "",
        "## Verified configurations",
        "",
        "Choose an exact recorded configuration to see its command and expected result. These selectors are "
        "generated from the authoritative verification cards and never synthesize combinations.",
    ]
    multiple_models = len(models) > 1
    for model in models:
        entries = [_mapping(entry, "model entry") for entry in model["entries"]]
        lines.extend(["", f'<a id="verified-{model["slug"]}"></a>'])
        if multiple_models:
            hf_id = str(model["hf_id"])
            model_label = hf_id.partition("/")[2] or hf_id
            lines.extend([f"### {_md_cell(model_label)}", ""])
        lines.extend(_model_explorer(entries, heading_level=4 if multiple_models else 3))
    lines.extend([MODEL_SECTION_END, ""])
    return "\n".join(lines).rstrip() + "\n"


def _merge_model_page(content: str, section: str, *, title: str | None = None) -> str:
    """Keep the original page introduction and replace its remaining sections."""
    has_start = MODEL_SECTION_START in content
    has_end = MODEL_SECTION_END in content
    if has_start != has_end:
        raise CatalogError("canonical model guide has an incomplete generated verification block")
    if has_start:
        introduction = content.partition(MODEL_SECTION_START)[0].rstrip()
    else:
        first_section = re.search(r"^## .+$", content, re.MULTILINE)
        introduction = content[: first_section.start()].rstrip() if first_section else content.rstrip()
    introduction = "\n".join(line.rstrip() for line in introduction.splitlines())
    introduction = re.sub(r"\[([^\]]+)\]\(#[^)]+\)", r"\1", introduction)
    if not re.search(r"^# .+$", introduction, re.MULTILINE):
        raise CatalogError("canonical model guide must have a level-one title")
    if title is not None:
        introduction = re.sub(r"^# .+$", f"# {title}", introduction, count=1, flags=re.MULTILINE)
    return f"{introduction}\n\n{section.rstrip()}\n"


def _render_nav_section() -> str:
    return ""


def _update_nav(nav_text: str) -> str:
    has_start = NAV_START in nav_text
    has_end = NAV_END in nav_text
    if has_start != has_end:
        raise CatalogError("Fern navigation has an incomplete generated model verification block")
    if not has_start:
        return nav_text
    pattern = re.compile(rf"{re.escape(NAV_START)}.*?{re.escape(NAV_END)}\n?", re.DOTALL)
    return pattern.sub(_render_nav_section(), nav_text)


def expected_outputs(repo_root: Path, catalog: dict[str, object]) -> dict[Path, str]:
    """Return every generated artifact and its deterministic content."""
    outputs = {
        repo_root / "docs/models/README.md": render_supported_models_page(catalog, repo_root, fern=False),
        repo_root / "docs/fern/versions/nightly/pages/models/README.mdx": render_supported_models_page(
            catalog, repo_root, fern=True
        ),
        repo_root / "docs/_static/model-verification/catalog-v1.json": json.dumps(catalog, indent=2, sort_keys=True)
        + "\n",
    }
    canonical_groups: dict[str, list[dict[str, object]]] = {}
    for raw_model in catalog["models"]:
        model = _mapping(raw_model, "catalog model")
        canonical_groups.setdefault(_find_model_doc(repo_root, model), []).append(model)
    for model_doc, models in canonical_groups.items():
        section = render_model_section(models)
        sphinx_path = repo_root / "docs" / model_doc
        fern_relative = Path(model_doc).with_suffix(".mdx")
        fern_path = repo_root / "docs/fern/versions/nightly/pages" / fern_relative
        if len(models) != 1:
            raise CatalogError(f"canonical model guide must map to exactly one card: {model_doc}")
        model = models[0]
        source_path = sphinx_path
        if not source_path.is_file():
            intro_source = MODEL_INTRO_SOURCES.get(str(model["slug"]))
            if intro_source is None:
                raise CatalogError(f"canonical model guide is missing for {model_doc}")
            source_path = repo_root / "docs" / intro_source
        title = MODEL_PAGE_TITLES.get(str(model["slug"]))
        merged_page = _merge_model_page(source_path.read_text(encoding="utf-8"), section, title=title)
        outputs[sphinx_path] = merged_page
        outputs[fern_path] = merged_page
    nav_path = repo_root / "docs/fern/versions/nightly.yml"
    outputs[nav_path] = _update_nav(nav_path.read_text(encoding="utf-8"))
    return outputs


def generate(repo_root: Path, *, check: bool) -> bool:
    """Write generated outputs, or return whether checked-in outputs match."""
    catalog = build_catalog(repo_root)
    outputs = expected_outputs(repo_root, catalog)
    mismatches: list[str] = []
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                mismatches.append(path.relative_to(repo_root).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for pattern in (
        "docs/model-verification/index.md",
        "docs/model-verification/models/*.md",
        "docs/fern/versions/nightly/pages/model-verification/index.mdx",
        "docs/fern/versions/nightly/pages/model-verification/models/*.mdx",
    ):
        for path in repo_root.glob(pattern):
            if check:
                mismatches.append(path.relative_to(repo_root).as_posix())
            elif path.read_text(encoding="utf-8").startswith(GENERATED_NOTICE):
                path.unlink()
    for retired_doc in RETIRED_COMBINED_MODEL_DOCS:
        for relative_path in (Path("docs") / retired_doc, Path("docs/fern/versions/nightly/pages") / retired_doc):
            path = repo_root / relative_path.with_suffix(".mdx" if "fern" in relative_path.parts else ".md")
            if not path.exists():
                continue
            if check:
                mismatches.append(path.relative_to(repo_root).as_posix())
            else:
                path.unlink()
    if mismatches:
        LOGGER.error("generated model verification files are stale: %s", ", ".join(sorted(mismatches)))
        return False
    if not check:
        LOGGER.info(
            "updated %d canonical model guides with %d concrete entries",
            len({_find_model_doc(repo_root, _mapping(model, "model")) for model in catalog["models"]}),
            sum(len(_mapping(model, "model")["entries"]) for model in catalog["models"]),
        )
    return True


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[2],
        help="Megatron Bridge repository root",
    )
    parser.add_argument("--check", action="store_true", help="fail when checked-in generated files are stale")
    return parser.parse_args()


def main() -> int:
    """Run the catalog generator command-line interface."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    args = _parse_args()
    try:
        return 0 if generate(args.repo_root.resolve(), check=args.check) else 1
    except (CatalogError, OSError, yaml.YAMLError) as error:
        LOGGER.error("%s", error)
        return 1


if __name__ == "__main__":
    sys.exit(main())
