class CatalogError(ValueError):
    """Raised when a card cannot be normalized without inventing information."""


def _mapping(value: object, context: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise CatalogError(f"{context} must be a mapping")
    return value


def _text(value: object | None) -> str | None:
    if value is None:
        return None
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return str(value)


def _json_value(value: object) -> object:
    if isinstance(value, dict):
        return {str(key): _json_value(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_json_value(item) for item in value]
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return value


def _slug(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug or "entry"


def _commands(item: dict[str, Any], context: str) -> list[str]:
    command = item.get("command")
    commands = item.get("commands")
    if command is not None and commands is not None:
        raise CatalogError(f"{context} has both command and commands")
    if command is not None:
        return [str(command).strip()]
    if commands is None:
        return []
    if not isinstance(commands, list) or not all(isinstance(value, str) for value in commands):
        raise CatalogError(f"{context}.commands must be a list of strings")
    return [value.strip() for value in commands]


def _flag_value(tokens: list[str], aliases: tuple[str, ...]) -> str | None:
    for index, token in enumerate(tokens):
        for alias in aliases:
            if token == alias and index + 1 < len(tokens):
                return tokens[index + 1]
            if token.startswith(f"{alias}="):
                return token.split("=", 1)[1]
    return None


def command_topology(command: str) -> dict[str, object]:
    """Extract only topology values explicitly present in one command."""
    try:
        tokens = shlex.split(command)
    except ValueError:
        tokens = command.split()
    topology: dict[str, object] = {}
    for name, aliases in TOPOLOGY_FLAGS.items():
        value = _flag_value(tokens, aliases)
        if value is not None:
            topology[name] = value
    nodes = topology.get("nodes")
    gpus_per_node = topology.get("gpus_per_node")
    if isinstance(nodes, str) and isinstance(gpus_per_node, str) and nodes.isdigit() and gpus_per_node.isdigit():
        topology["total_gpus"] = int(nodes) * int(gpus_per_node)
    return topology


def _entry(
    *,
    model_slug: str,
    workflow: str,
    hardware: str | None,
    variant: str | None,
    source_pointer: str,
    item: dict[str, Any],
    inherited: dict[str, Any],
    dimensions: dict[str, object] | None = None,
) -> dict[str, object]:
    merged = {**inherited, **item}
    status = _text(merged.get("status"))
    if status not in VALID_STATUSES:
        raise CatalogError(f"{source_pointer}.status must be one of {sorted(VALID_STATUSES)}")
    commands = _commands(merged, source_pointer)
    identity = [model_slug, workflow]
    if hardware:
        identity.append(hardware)
    if variant:
        identity.append(variant)
    entry_id = _slug("-".join(identity))
    return {
        "entry_id": entry_id,
        "source_pointer": source_pointer,
        "workflow": workflow,
        "hardware": hardware,
        "variant": variant,
        "status": status,
        "precision": _text(merged.get("precision")),
        "last_verified": _text(merged.get("last_verified")),
        "bridge_commit": _text(merged.get("bridge_commit")),
        "commands": commands,
        "command_topologies": [command_topology(command) for command in commands],
        "dimensions": _json_value(dimensions or {}),
        "enabled_features": _json_value(merged.get("enabled_features", {})),
        "metrics": _json_value(merged.get("metrics", {})),
        "expected_result": _text(merged.get("expected_result")),
    }


def _normal_item_entries(
    model_slug: str,
    workflow: str,
    hardware: str | None,
    source_pointer: str,
    item: dict[str, Any],
    inherited: dict[str, Any],
) -> list[dict[str, object]]:
    if "variants" in item:
        variants = _mapping(item["variants"], f"{source_pointer}.variants")
        parent = {**inherited, **{key: value for key, value in item.items() if key != "variants"}}
        return [
            _entry(
                model_slug=model_slug,
                workflow=workflow,
                hardware=hardware,
                variant=str(name),
                source_pointer=f"{source_pointer}.variants.{name}",
                item=_mapping(value, f"{source_pointer}.variants.{name}"),
                inherited=parent,
            )
            for name, value in variants.items()
        ]
    if "points" in item:
        points = item["points"]
        if not isinstance(points, list):
            raise CatalogError(f"{source_pointer}.points must be a list")
        parent = {**inherited, **{key: value for key, value in item.items() if key != "points"}}
        entries = []
        for index, point_value in enumerate(points):
            point = _mapping(point_value, f"{source_pointer}.points[{index}]")
            num_gpus = point.get("num_gpus")
            variant = f"{num_gpus}-gpu" if num_gpus is not None else f"point-{index + 1}"
            dimensions = {
                str(key): _json_value(value)
                for key, value in point.items()
                if key
                not in {
                    "status",
                    "precision",
                    "last_verified",
                    "bridge_commit",
                    "command",
                    "commands",
                    "metrics",
                    "enabled_features",
                    "expected_result",
                }
            }
            entries.append(
                _entry(
                    model_slug=model_slug,
                    workflow=workflow,
                    hardware=hardware,
                    variant=variant,
                    source_pointer=f"{source_pointer}.points[{index}]",
                    item=point,
                    inherited=parent,
                    dimensions=dimensions,
                )
            )
        return entries
    return [
        _entry(
            model_slug=model_slug,
            workflow=workflow,
            hardware=hardware,
            variant=None,
            source_pointer=source_pointer,
            item=item,
            inherited=inherited,
        )
    ]


def normalize_card(card_path: Path, repo_root: Path) -> dict[str, object]:
    """Normalize one YAML card into exact concrete configurations."""
    with card_path.open(encoding="utf-8") as stream:
        card = _mapping(yaml.safe_load(stream), str(card_path))
    model = _mapping(card.get("model"), f"{card_path}: model")
    environment = _mapping(card.get("verification_environment"), f"{card_path}: verification_environment")
    items = _mapping(card.get("items"), f"{card_path}: items")
    model_slug = card_path.parent.name
    entries: list[dict[str, object]] = []
    inherited = {"bridge_commit": environment.get("bridge_commit")}
    for workflow, raw_item in items.items():
        item = _mapping(raw_item, f"items.{workflow}")
        source_pointer = f"items.{workflow}"
        if "status" in item and any(key in item for key in ("command", "commands", "variants", "points")):
            entries.extend(_normal_item_entries(model_slug, workflow, None, source_pointer, item, inherited))
            continue
        for hardware, raw_hardware_item in item.items():
            hardware_item = _mapping(raw_hardware_item, f"{source_pointer}.{hardware}")
            entries.extend(
                _normal_item_entries(
                    model_slug,
                    workflow,
                    str(hardware),
                    f"{source_pointer}.{hardware}",
                    hardware_item,
                    inherited,
                )
            )
    pointers = [str(entry["source_pointer"]) for entry in entries]
    entry_ids = [str(entry["entry_id"]) for entry in entries]
    if len(pointers) != len(set(pointers)):
        raise CatalogError(f"{card_path} contains duplicate normalized source pointers")
    if len(entry_ids) != len(set(entry_ids)):
        raise CatalogError(f"{card_path} produces duplicate entry ids")
    return {
        "slug": model_slug,
        "title": _text(card.get("title")) or model_slug,
        "summary": _text(card.get("summary")) or "",
        "source_card": card_path.relative_to(repo_root).as_posix(),
        "hf_id": _text(model.get("hf_id")) or "",
        "hf_revision": _text(model.get("hf_revision")),
        "architecture": _text(model.get("architecture")),
        "min_transformers_version": _text(model.get("min_transformers_version")),
        "base_container": _text(environment.get("base_container")),
        "bridge_commit": _text(environment.get("bridge_commit")),
        "entries": entries,
    }


def build_catalog(repo_root: Path) -> dict[str, object]:
    """Discover all cards and build the versioned normalized catalog."""
    cards = sorted(repo_root.glob(CARD_GLOB))
    if not cards:
        raise CatalogError(f"no cards matched {CARD_GLOB}")
    models = [normalize_card(card, repo_root) for card in cards]
    models.sort(key=lambda model: (str(model["hf_id"]).casefold(), str(model["slug"])))
    return {
        "schema_version": CATALOG_SCHEMA_VERSION,
        "source": CARD_GLOB,
        "generation": "offline-derived; YAML cards remain authoritative",
        "models": models,
    }


def _md_cell(value: object | None) -> str:
    if value is None or value == "":
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _status_label(status: str) -> str:
    return STATUS_LABELS[status]


def _model_status(entries: list[dict[str, object]]) -> str:
    statuses = {str(entry["status"]) for entry in entries}
    if statuses == {"verified"}:
        return "verified"
    if "verified" in statuses:
        return "partially verified"
    for status in ("unverified", "unsupported", "not_applicable"):
        if status in statuses:
            return status.replace("_", " ")
    raise CatalogError("model has no concrete configuration status")


def _find_model_doc(repo_root: Path, model: dict[str, object]) -> str:
    override = MODEL_PAGE_PATHS.get(str(model["slug"]))
    if override:
        return override
    needles = [str(model["source_card"]), str(model["hf_id"]), str(model["slug"])]
    candidates: list[tuple[int, int, str]] = []
    for path in sorted((repo_root / "docs/models").rglob("*.md")):
        content = path.read_text(encoding="utf-8")
        score = sum((3 - index) for index, needle in enumerate(needles) if needle and needle in content)
        if score:
            relative = path.relative_to(repo_root / "docs").as_posix()
            candidates.append((-score, len(relative), relative))
    if not candidates:
        return "models/README.md"
    return min(candidates)[2]


def _status_badge(status: str, label: str | None = None) -> str:
    presentations = {
        "verified": ("✓", "Verified"),
        "partial": ("◐", "Partial"),
        "unverified": ("○", "Unverified"),
        "unsupported": ("×", "Unsupported"),
        "not-applicable": ("—", "Not applicable"),
    }
    icon, status_label = presentations[status]
    text = f"{label} {icon}" if label else f"{icon} {status_label}"
    return (
        f'<span class="verification-status verification-status--{status}" title="{status_label}">'
        f"{html.escape(text)}</span>"
    )


def _directory_status(entries: list[dict[str, object]]) -> str:
    model_status = _model_status(entries)
    if model_status == "partially verified":
        return "partial"
    return model_status.replace("_", "-").replace(" ", "-")


def _model_directory(catalog: dict[str, object], repo_root: Path, *, fern: bool) -> list[str]:
    providers: dict[str, list[dict[str, object]]] = {}
    for raw_model in catalog["models"]:
        model = _mapping(raw_model, "catalog model")
        owner = str(model["hf_id"]).partition("/")[0]
        providers.setdefault(owner, []).append(model)
    lines = [
        "## Models",
        "",
        "Choose a model to inspect its recorded import/export, training, and precision combinations.",
        "",
        '<div class="verification-provider-grid verification-model-directory">',
    ]
    for owner, models in providers.items():
        owner_label = OWNER_LABELS.get(owner.casefold(), owner)
        lines.extend(
            [
                '  <section class="verification-provider-card">',
                '    <header class="verification-provider-heading">',
                f"      <strong>{html.escape(owner_label)}</strong>",
                f"      <span>{len(models)} model{'s' if len(models) != 1 else ''}</span>",
                "    </header>",
                '    <div class="verification-provider-models">',
            ]
        )
        for model in models:
            hf_id = str(model["hf_id"])
            _, separator, model_name = hf_id.partition("/")
            if not separator:
                model_name = hf_id
            model_doc = _find_model_doc(repo_root, model)
            suffix = "" if fern else ".html"
            relative_model_doc = model_doc.removeprefix("models/").removesuffix(".md")
            href = f"{relative_model_doc}{suffix}#verified-{model['slug']}"
            entries = [_mapping(entry, f"{model['slug']} entry") for entry in model["entries"]]
            status = _directory_status(entries)
            allowlist_suffix = (
                " <!-- pragma: allowlist secret -->" if model_name in DETECT_SECRETS_ALLOWLIST_MODEL_NAMES else ""
            )
            lines.extend(
                [
                    f'      <a class="verification-model-link" href="{href}">',
                    f'        <strong title="{html.escape(hf_id, quote=True)}">{html.escape(model_name)}</strong>'
                    f"{allowlist_suffix}",
                    f"        {_status_badge(status)}",
                    "      </a>",
                ]
            )
        lines.extend(["    </div>", "  </section>"])
    lines.extend(["</div>", ""])
    return lines


def _entry_capability(entry: dict[str, object]) -> tuple[str, str] | None:
    workflow = str(entry["workflow"])
    for capability_id, capability_label, workflows in CAPABILITY_TABS:
        if workflow in workflows:
            return capability_id, capability_label
    return None


